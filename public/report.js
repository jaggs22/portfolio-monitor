/* report.js: the Detailed Sell-Side Analysis. A sell-side style initiation on A4 assembled from the same research the
   Quick view shows: review text, segment data from filings, the live peer table, statements, scenarios and risks.
   Nothing new is invented here; every number is read from the data the app already holds. Print saves it as a PDF. */
(function () {
  'use strict';
  const { h, fmt, MARK } = window.UI;
  const F = window.Fin, E = window.Engine;
  const num = fmt.num;

  window.makeReport = function (CO, kit) {
    const { state, nameOf } = kit;

    const brandBar = (date, pageNo, of) => h('header', { class: 'rp-band' },
      h('div', { class: 'rp-brand' }, h('span', { class: 'rp-mark', html: MARK }), h('span', null, h('b', null, 'Moat Monitor'), h('small', null, 'AI Native Equity Research Solution'))),
      h('div', { class: 'rp-band-r' }, h('span', null, 'Company report'), h('span', null, date), h('span', null, `Page ${pageNo} of ${of}`)));
    const foot = (t) => h('footer', { class: 'rp-foot' }, h('span', null, `${nameOf(t)} (${t}) · Initiation of coverage · Generated by Moat Monitor from SEC filings and Yahoo Finance market data.`), h('span', null, 'Not investment advice. See disclosures.'));
    const sec = (title, ...kids) => h('section', { class: 'rp-sec' }, h('h3', null, title), ...kids);
    const table = (head, rows, opts) => h('table', { class: 'rp-tbl ' + ((opts && opts.cls) || '') },
      h('thead', null, h('tr', null, head.map((x, i) => h('th', { class: i ? '' : 'l' }, x)))),
      h('tbody', null, rows.map((r) => h('tr', { class: r.cls || '' }, (r.cells || r).map((c, i) => h(i ? 'td' : 'th', { class: i ? '' : 'l' }, c))))));
    const kv = (rows) => h('dl', { class: 'rp-kv' }, rows.filter(Boolean).map(([k, v]) => h('div', null, h('dt', null, k), h('dd', null, v))));

    function keyData(t) {
      const p = CO.priceOf(t), f = CO.dat(t, 'fundamentals'), ps = CO.peerStats(t), ev = CO.evalFor(t, false), r = CO.researchOf(t);
      const s = CO.finSnapshot(t);
      const v = f && p ? F.valuation(f, p.price, f.profile) : null;
      const prof = (f && f.profile) || {};
      const hist = CO.dat(t, 'history');
      const st = hist && hist.stats;
      const next = r && (r.catalysts || []).filter((c) => c.date >= new Date().toISOString().slice(0, 10)).sort((a, b) => a.date.localeCompare(b.date))[0];
      return kv([
        ev ? ['Engine stance', `${ev.stance} · ${ev.conviction} conviction`] : ['Coverage', 'Basic view'],
        ['Price', p ? fmt.px(p.price) : '–'],
        ev ? ['Base-case value', `${fmt.px(ev.scenarios.base.exitPrice)} in ${r.horizon} yrs`] : null,
        ev ? ['Expected return', `${fmt.pct(ev.expectedIrr)} a yr vs ${fmt.pct(ev.hurdle)} hurdle`] : null,
        ['Market cap', v ? fmt.usdM(v.mcap) : '–'],
        ['Enterprise value', v ? fmt.usdM(v.ev) : '–'],
        ps && ps.me ? ['NTM EV/EBITDA', `${fmt.mult(ps.me.ntm.ev_ebitda)} (peers ${fmt.mult(ps.med('ntm', 'ev_ebitda'))})`] : ['EV/EBITDA (LTM)', v ? fmt.mult(v.ev_ebitda) : '–'],
        ps && ps.me ? ['NTM P/E', `${fmt.mult(ps.me.ntm.pe)} (peers ${fmt.mult(ps.med('ntm', 'pe'))})`] : ['P/E (LTM)', v ? fmt.mult(v.pe) : '–'],
        ['Dividend yield', v ? fmt.pct(v.div_yield) : '–'],
        ['Net debt / EBITDA', s && num(s.ndE) !== null ? (s.ndE < 0 ? 'Net cash' : fmt.mult(s.ndE)) : '–'],
        ['52-week range', st && num(st.lo52) ? `${fmt.px(st.lo52)} – ${fmt.px(st.hi52)}` : prof.lo52 ? `${fmt.px(prof.lo52)} – ${fmt.px(prof.hi52)}` : '–'],
        ['Consensus target', num(prof.target_mean) ? `${fmt.px(prof.target_mean)} (${prof.analyst_count || '–'} analysts)` : '–'],
        next ? ['Next event', `${next.label.replace(/ \(.*\)/, '')}, ${fmt.date(next.date)}${next.confirmed ? '' : ' (unconfirmed)'}`] : null
      ]);
    }

    function scenarioTable(t) {
      const ev = CO.evalFor(t, false), rv = CO.review(t), r = CO.researchOf(t);
      if (!ev) return null;
      const sc = ev.scenarios, pr = ev.probs;
      const story = (k) => (rv && rv.scenarios[k === 'bear' ? 'downside' : k === 'bull' ? 'upside' : 'base']) || null;
      return table(['Scenario', 'Odds', 'Value', 'Return a yr', 'What it takes'],
        ['bear', 'base', 'bull'].map((k) => [k === 'bear' ? 'Downside' : k === 'bull' ? 'Upside' : 'Base', fmt.pct(pr[k], 0), fmt.px(sc[k].exitPrice), fmt.spct(sc[k].irr), story(k) ? story(k).needs : `${(sc[k].g * 100).toFixed(1)}% growth, ${sc[k].pe.toFixed(0)}x exit`]),
        { cls: 'wrap-last' });
    }

    function segTable(t) {
      const rv = CO.review(t);
      const kind = rv && rv.mix ? rv.mix.axis : 'segment';
      const v = CO.mixView(t, 'quarterly', kind) || CO.mixView(t, 'annual', kind);
      const rows = CO.mappedRows(t, v).filter((x) => x.row.revenue > 0);
      if (!rows.length) return null;
      const total = rows.reduce((a, x) => a + x.row.revenue, 0);
      const hasP = rows.some((x) => x.row.profit != null);
      const head = ['', 'Revenue', 'Share', 'Growth'].concat(hasP ? ['Margin', 'Chg', 'EBITDA'] : []).concat(['What drives it']);
      const body = rows.map((x) => [x.label, fmt.usdM(x.row.revenue), fmt.pct(x.row.revenue / total, 0), fmt.spct(x.row.growth, 0)]
        .concat(hasP ? [fmt.pct(x.row.margin), x.row.margin != null && x.row.margin_prior != null ? fmt.pts(x.row.margin - x.row.margin_prior, 1) : '–', fmt.usdM(x.row.ebitda)] : [])
        .concat([x.driver || '']));
      return h('div', null,
        h('div', { class: 'rp-mix' }, rows.map((x, i) => h('i', { class: 'm' + (i % 6), style: { width: (x.row.revenue / total * 100).toFixed(2) + '%' } }))),
        table(head, body, { cls: 'wrap-last' }),
        h('p', { class: 'rp-note' }, `${CO.periodLabel(v)}, against the same period a year earlier. ${rv && rv.mix ? rv.mix.note : ''}`));
    }

    function finTable(t) {
      const f = CO.dat(t, 'fundamentals');
      if (!f || !f.annual) return null;
      const A = f.annual, n = A.period_ends.length, from = Math.max(0, n - 4);
      const D = F.derive(f, 'annual'), Q = F.derive(f, 'quarterly');
      const ends = A.period_ends.slice(from);
      const col = (k) => (A.rows[k] || []).slice(from);
      const dcol = (k) => (D[k] || []).slice(from);
      const ttm = f.ttm || {};
      const last = (xs) => { for (let i = xs.length - 1; i >= 0; i--) if (num(xs[i]) !== null) return xs[i]; return null; };
      const r4 = F.rolling4((f.quarterly && f.quarterly.rows.revenue) || []);
      const ttmGrowth = r4.length > 4 && r4[r4.length - 5] ? r4[r4.length - 1] / r4[r4.length - 5] - 1 : null;
      const m = (v) => fmt.usdM(v);
      const rows = [
        ['Revenue', ...col('revenue').map(m), m(ttm.revenue)],
        { cells: ['Growth', ...dcol('rev_growth').map((x) => fmt.spct(x, 1)), fmt.spct(ttmGrowth, 1)], cls: 'sub' },
        ['Operating income', ...col('op_income').map(m), m(ttm.op_income)],
        { cells: ['Operating margin', ...dcol('op_margin').map((x) => fmt.pct(x)), num(ttm.op_income) && ttm.revenue ? fmt.pct(ttm.op_income / ttm.revenue) : '–'], cls: 'sub' },
        ['EBITDA', ...col('ebitda').map(m), m(ttm.ebitda)],
        ['Net income', ...col('net_income').map(m), m(ttm.net_income)],
        ['Diluted EPS', ...col('eps_diluted').map((x) => (num(x) === null ? '–' : '$' + x.toFixed(2))), num(ttm.eps_diluted) ? '$' + ttm.eps_diluted.toFixed(2) : '–'],
        ['Free cash flow', ...col('fcf').map(m), m(ttm.fcf)],
        { cells: ['ROIC', ...dcol('roic').map((x) => fmt.pct(x)), fmt.pct(last(Q.roic))], cls: 'sub' },
        { cells: ['Net debt / EBITDA', ...dcol('net_debt_ebitda').map((x) => (num(x) === null ? '–' : x.toFixed(1) + 'x')), num(last(Q.net_debt_ebitda)) ? last(Q.net_debt_ebitda).toFixed(1) + 'x' : '–'], cls: 'sub' }
      ];
      return h('div', null, table(['USD', ...ends.map((e) => 'FY' + e.slice(2, 4)), 'LTM'], rows, { cls: 'num' }),
        h('p', { class: 'rp-note' }, `Company-reported GAAP figures from SEC filings, as of ${(f.asof || '').slice(0, 10)}. ROIC is after tax on reported invested capital.`));
    }

    function peerTable(t) {
      const ps = CO.peerStats(t);
      if (!ps || !ps.me) return null;
      const order = [ps.me].concat(ps.peers);
      const f = (v) => fmt.mult(v);
      const rows = order.map((r) => ({ cells: [r.name, fmt.usdB(r.mcap_usd_b), f(r.ntm.ev_ebitda), f(r.ntm.pe), f(r.ntm.ev_fcf), fmt.pct(r.ebitda_margin, 0), fmt.spct(r.ntm.rev_growth, 0), fmt.pct(r.roic, 0)], cls: r.role === 'subject' ? 'me' : '' }));
      const med = (blk, k) => ps.med(blk, k);
      rows.push({ cells: [`Peer median (${ps.peers.length})`, '', f(med('ntm', 'ev_ebitda')), f(med('ntm', 'pe')), f(med('ntm', 'ev_fcf')), fmt.pct(med(null, 'ebitda_margin'), 0), fmt.spct(med('ntm', 'rev_growth'), 0), fmt.pct(med(null, 'roic'), 0)], cls: 'med' });
      const prem = (k) => (ps.me.ntm[k] && med('ntm', k) ? fmt.spct(ps.me.ntm[k] / med('ntm', k) - 1, 0) : '–');
      rows.push({ cells: ['Premium to median', '', prem('ev_ebitda'), prem('pe'), prem('ev_fcf'), '', '', ''], cls: 'med' });
      return h('div', null, table(['Next 12 months', 'Mkt cap', 'EV/EBITDA', 'P/E', 'EV/FCF', 'EBITDA mgn', 'Growth', 'ROIC'], rows, { cls: 'num' }),
        h('p', { class: 'rp-note' }, `Yahoo Finance via the Moat Monitor pipeline, ${fmt.date(ps.doc.asof)}. EBITDA excludes unusual items; NTM P/E on consensus EPS. Peer set as selected in the app.`));
    }

    function assumptions(t) {
      const r = CO.researchOf(t), rv = CO.review(t);
      if (!r) return null;
      return table(['Assumption', 'Downside', 'Base', 'Upside', 'Basis'], E.DRIVERS.map((k) => {
        const d = r.drivers[k], meta = E.DRIVER_META[k];
        const u = (x) => `${x}${meta.unit === '%' || meta.unit === '% a year' ? '%' : meta.unit === 'x' ? 'x' : ' ' + meta.unit}`;
        return [meta.label, u(d.bear), u(d.base), u(d.bull), rv && rv.forecast_basis ? rv.forecast_basis[k] : d.kind === 'sourced' ? 'Sourced from filings' : 'Engine judgment'];
      }), { cls: 'wrap-last' });
    }

    function risks(t) {
      const r = CO.researchOf(t), rv = CO.review(t);
      if (!r) return null;
      const by = {};
      (r.tripwires || []).forEach((x) => { by[x.id] = x; });
      if (rv) return table(['What could break', 'How it would show', 'Watch', 'Status'], rv.risks.map((x) => {
        const tw = x.trip ? by[x.trip] : null;
        return [x.cause, x.how, x.watch, tw ? CO.tripStatus(tw) : 'Monitor'];
      }), { cls: 'wrap' });
      return table(['Risk'], (r.risks || []).map((x) => [x]), { cls: 'wrap' });
    }

    function mgmt(t) {
      const m = CO.dat(t, 'mgmt'), rv = CO.review(t);
      if (!m) return null;
      const sp = m.surprises || {}, cap = m.capital || {};
      const eq = (m.components || []).find((c) => c.key === 'earnings_quality') || {};
      const gov = (m.components || []).find((c) => c.key === 'governance') || {};
      const cc = eq.note ? (eq.note.match(/([\d.]+)x net income/) || [])[1] : null;
      const g = gov.note ? (gov.note.match(/([\d.]+) of 10/) || [])[1] : null;
      return h('div', null,
        h('div', { class: 'rp-evs' },
          h('div', null, h('b', null, sp.n ? `${sp.beats}/${sp.n}` : '–'), h('span', null, 'quarters beat consensus')),
          h('div', null, h('b', null, cc ? cc + 'x' : '–'), h('span', null, 'cash flow to net income, 5 yrs')),
          h('div', null, h('b', null, cap.share_change_pct_pa != null ? fmt.spct(cap.share_change_pct_pa / 100, 1) : '–'), h('span', null, 'share count a year')),
          h('div', null, h('b', null, g ? g + '/10' : '–'), h('span', null, 'ISS governance risk'))),
        rv ? h('ul', { class: 'rp-list' }, rv.flags.map((x) => h('li', null, h('b', null, x.flag + '. '), x.evidence))) : null);
    }

    /* One-year share price, drawn as plain SVG so it prints identically in light or dark mode. */
    function priceChart(t) {
      const hist = CO.dat(t, 'history');
      if (!hist || !hist.bars || hist.bars.length < 20) return null;
      const bars = CO.sliceBars(hist.bars, '1Y');
      const ys = bars.map((b) => b[4]), W = 470, H = 120, lo = Math.min(...ys), hi = Math.max(...ys), sp = hi - lo || 1;
      const X = (i) => (i / (ys.length - 1)) * W, Y = (v) => 8 + (1 - (v - lo) / sp) * (H - 24);
      const d = ys.map((v, i) => (i ? 'L' : 'M') + X(i).toFixed(1) + ' ' + Y(v).toFixed(1)).join('');
      const ret = ys[ys.length - 1] / ys[0] - 1;
      const dt = (s) => new Date(s * 1000).toLocaleDateString('en-GB', { month: 'short', year: '2-digit', timeZone: 'UTC' });
      const svg = `<svg viewBox="0 0 ${W} ${H}" width="100%" preserveAspectRatio="none" style="display:block;height:${H}px">`
        + `<line x1="0" x2="${W}" y1="${Y(hi)}" y2="${Y(hi)}" stroke="#e2e0db"/><line x1="0" x2="${W}" y1="${Y(lo)}" y2="${Y(lo)}" stroke="#e2e0db"/>`
        + `<path d="${d}" fill="none" stroke="#1d1d1b" stroke-width="1.4" vector-effect="non-scaling-stroke"/></svg>`;
      return h('div', null, h('div', { class: 'rp-chart', html: svg }),
        h('div', { class: 'rp-chart-ax' }, h('span', null, dt(bars[0][0])), h('span', null, `High ${fmt.px(hi)} · Low ${fmt.px(lo)} · ${fmt.spct(ret, 1)} over the year`), h('span', null, dt(bars[bars.length - 1][0]))));
    }

    function pageWrap(t, n, of, ...kids) {
      return h('article', { class: 'rp-page' }, brandBar(fmt.date(new Date().toISOString().slice(0, 10)), n, of), h('div', { class: 'rp-body' }, ...kids), foot(t));
    }

    /* ---------- initiation pieces ---------- */
    const RK = (x) => (x === 'Overweight' ? 'ow' : x === 'Underweight' ? 'uw' : 'ew');
    const eps = (x) => (num(x) === null ? '–' : '$' + x.toFixed(2));
    const lightDot = (l) => h('span', { class: 'rp-dot ' + l });

    function callBox(t) {
      const c = CO.callOf(t, false), p = CO.priceOf(t), f = CO.dat(t, 'fundamentals'), ps = CO.peerStats(t), s = CO.finSnapshot(t);
      const v = f && p ? F.valuation(f, p.price, f.profile) : null, prof = (f && f.profile) || {}, st = (CO.dat(t, 'history') || {}).stats || {};
      return h('aside', { class: 'rp-side' },
        h('div', { class: 'rp-rating ' + RK(c.rating) }, h('small', null, 'Rating'), h('b', null, c.rating)),
        h('div', { class: 'rp-pt' }, h('small', null, '12-month price target'), h('b', null, fmt.px(c.pt))),
        kv([
          ['Price', p ? fmt.px(p.price) : '–'],
          ['Upside to target', fmt.spct(c.upside, 1)],
          ['Total return incl. dividend', fmt.spct(c.totalReturn, 1)],
          ['Cost of equity', fmt.pct(c.hurdle)],
          ['Downside / upside case', `${fmt.px(c.bear.value)} / ${fmt.px(c.bull.value)}`]]),
        h('h3', null, 'Key data'),
        kv([
          ['Market cap', v ? fmt.usdM(v.mcap) : '–'],
          ['Enterprise value', v ? fmt.usdM(v.ev) : '–'],
          ['52-week range', num(st.lo52) ? `${fmt.px(st.lo52)} – ${fmt.px(st.hi52)}` : prof.lo52 ? `${fmt.px(prof.lo52)} – ${fmt.px(prof.hi52)}` : '–'],
          ['Dividend yield', v ? fmt.pct(v.div_yield) : '–'],
          ['Net debt / EBITDA', s && num(s.ndE) !== null ? (s.ndE < 0 ? 'Net cash' : fmt.mult(s.ndE)) : '–'],
          ps && ps.me ? ['NTM EV/EBITDA', `${fmt.mult(ps.me.ntm.ev_ebitda)} (peers ${fmt.mult(ps.med('ntm', 'ev_ebitda'))})`] : null,
          ['Street target', num(prof.target_mean) ? `${fmt.px(prof.target_mean)} (${prof.analyst_count || '–'} analysts)` : '–'],
          ['Benchmark', CO.benchOf(t)]]),
        h('h3', null, 'Moat Monitor framework'),
        h('div', { class: 'rp-fw' }, CO.framework(t).map((x) => h('div', null, lightDot(x.light), h('span', null, x.label), h('b', null, x.value)))));
    }

    function estimatesTable(t) {
      const e = CO.estimates(t), p = CO.priceOf(t);
      if (!e) return null;
      const R = e.rows, gap = (x) => (x == null ? '–' : fmt.spct(x, 1));
      const rows = [
        ['Revenue, ours', ...R.map((r) => fmt.usdM(r.rev))],
        { cells: ['Revenue, consensus', ...R.map((r) => (r.cRev ? fmt.usdM(r.cRev) : '–'))], cls: 'sub' },
        { cells: ['Difference', ...R.map((r) => gap(r.gapRev))], cls: 'sub' },
        ['EPS, ours', ...R.map((r) => eps(r.eps))],
        { cells: ['EPS, consensus', ...R.map((r) => (r.cEps ? eps(r.cEps) : '–'))], cls: 'sub' },
        { cells: ['Difference', ...R.map((r) => gap(r.gapEps))], cls: 'sub' },
        ['P/E on our EPS', ...R.map((r) => (p ? fmt.mult(p.price / r.eps) : '–'))],
        ['Dividend per share', ...R.map((r) => eps(r.dps))],
        { cells: ['Dividend yield', ...R.map((r) => (p ? fmt.pct(r.dps / p.price, 1) : '–'))], cls: 'sub' }];
      return h('div', null, table(['USD', ...R.map((r) => r.label)], rows, { cls: 'num' }),
        h('p', { class: 'rp-note' }, 'Ours: base case of the Moat Monitor scenario model. Consensus: Yahoo Finance analyst mean. P/E and yield at the current price.'));
    }

    /* Share price against its sector benchmark, both rebased to 100 a year ago. */
    function relChart(t) {
      const hist = CO.dat(t, 'history'), rp = CO.relPerf(t);
      if (!hist || !hist.bars || hist.bars.length < 20) return null;
      const bars = CO.sliceBars(hist.bars, '1Y'), t0 = bars[0][0];
      const bb = rp && rp.benchBars ? rp.benchBars.filter((b) => b[0] >= t0) : [];
      const a = bars.map((b) => [b[0], b[4] / bars[0][4] * 100]), b = bb.length ? bb.map((x) => [x[0], x[4] / bb[0][4] * 100]) : [];
      const all = a.concat(b).map((x) => x[1]), lo = Math.min(...all), hi = Math.max(...all), sp = hi - lo || 1;
      const W = 470, H = 130, x0 = a[0][0], x1 = a[a.length - 1][0];
      const X = (x) => ((x - x0) / (x1 - x0 || 1)) * W, Y = (v) => 8 + (1 - (v - lo) / sp) * (H - 20);
      const path = (pts) => pts.map((q, i) => (i ? 'L' : 'M') + X(q[0]).toFixed(1) + ' ' + Y(q[1]).toFixed(1)).join('');
      const dt = (z) => new Date(z * 1000).toLocaleDateString('en-GB', { month: 'short', year: '2-digit', timeZone: 'UTC' });
      const svg = `<svg viewBox="0 0 ${W} ${H}" width="100%" preserveAspectRatio="none" style="display:block;height:${H}px">`
        + `<line x1="0" x2="${W}" y1="${Y(100)}" y2="${Y(100)}" stroke="#e2e0db" stroke-dasharray="3 3"/>`
        + (b.length ? `<path d="${path(b)}" fill="none" stroke="#a7a59f" stroke-width="1.2" vector-effect="non-scaling-stroke"/>` : '')
        + `<path d="${path(a)}" fill="none" stroke="#1d1d1b" stroke-width="1.5" vector-effect="non-scaling-stroke"/></svg>`;
      return h('div', null, h('div', { class: 'rp-chart', html: svg }),
        h('div', { class: 'rp-chart-ax' }, h('span', null, dt(x0)), h('span', { class: 'rp-legend' }, h('i', { class: 'k' }), t, h('i', { class: 'g' }), rp ? rp.benchName + ' (' + rp.bench + ')' : ''), h('span', null, dt(x1))));
    }
    function perfTable(t) {
      const rp = CO.relPerf(t);
      if (!rp) return null;
      return table(['Performance', ...rp.rows.map((x) => x.k)], [
        ['Absolute', ...rp.rows.map((x) => fmt.spct(x.abs, 1))],
        ['Relative to ' + rp.bench, ...rp.rows.map((x) => fmt.spct(x.rel, 1))]], { cls: 'num' });
    }

    function frameworkTable(t) {
      const fw = CO.framework(t);
      if (!fw.length) return null;
      return h('div', null, table(['Test', 'Read', 'Reading', 'Basis'], fw.map((x) => [x.label, h('span', null, lightDot(x.light), x.light === 'g' ? 'Positive' : x.light === 'r' ? 'Negative' : 'Neutral'), x.value, x.why]), { cls: 'wrap-last' }),
        h('p', { class: 'rp-note' }, 'Fixed thresholds, the same for every company. Moat 4+ of 5 positive; growth 2 points ahead of peers; ROIC 15%+; net debt under 1.5x EBITDA; cash conversion 1.0x+; our EPS 3%+ above consensus; valuation at or below the peer median (above 25% premium negative); 12-month return 5 points ahead of the sector.'));
    }

    function targetBuild(t) {
      const c = CO.callOf(t, false), r = CO.researchOf(t), e = CO.estimates(t), p = CO.priceOf(t);
      const lab = e ? e.rows[1].label : 'Next year';
      return h('div', null,
        h('p', null, `We value ${nameOf(t)} on next-year earnings. The ${fmt.px(c.pt)} target is our ${lab} base-case EPS of ${eps(c.eps1)} times a target P/E of ${c.targetPE.toFixed(1)}x. That multiple moves one year's worth of the way from today's ${c.pe0.toFixed(1)}x toward the ${r.horizon}-year exit multiple in each scenario, so the target already prices in the de-rating or re-rating we expect. A year of dividends brings the total return to ${fmt.spct(c.totalReturn, 1)} against a ${fmt.pct(c.hurdle)} cost of equity. We rate Overweight when that return clears the cost of equity by 5 points or more, Underweight when it falls 5 points or more short, and Equal weight in between.`),
        table(['Case', 'EPS ' + lab, 'P/E', 'Value', 'vs price', 'What it takes'], [['bear', 'Downside'], ['base', 'Target'], ['bull', 'Upside']].map(([k, n]) => {
          const x = k === 'base' ? { eps1: c.eps1, pe: c.targetPE, value: c.pt } : c[k];
          const story = CO.review(t) && CO.review(t).scenarios[k === 'bear' ? 'downside' : k === 'bull' ? 'upside' : 'base'];
          return { cells: [n, eps(x.eps1), x.pe.toFixed(1) + 'x', fmt.px(x.value), p ? fmt.spct(x.value / p.price - 1, 1) : '–', story ? story.needs : ''], cls: k === 'base' ? 'me' : '' };
        }), { cls: 'wrap-last' }));
    }

    function riskTable(t) {
      const r = CO.researchOf(t), rv = CO.review(t);
      const by = {};
      (r.tripwires || []).forEach((x) => { by[x.id] = x; });
      return table(['Category', 'Downside risk', 'How it would show', 'Watch', 'Status'], rv.risks.map((x) => {
        const tw = x.trip ? by[x.trip] : null;
        return [x.cat || '', h('b', null, x.cause), x.how, x.watch, tw ? CO.tripStatus(tw) : 'Monitor'];
      }), { cls: 'wrap' });
    }

    function catalysts(t) {
      const r = CO.researchOf(t), today = new Date().toISOString().slice(0, 10);
      const cs = (r.catalysts || []).filter((c) => c.date >= today).sort((a, b) => a.date.localeCompare(b.date));
      if (!cs.length) return null;
      return table(['Date', 'Event', 'Importance', 'What we watch'], cs.map((c) => [fmt.date(c.date) + (c.confirmed ? '' : ' (unconfirmed)'), c.label, c.importance || '–', c.note || '']), { cls: 'wrap-last' });
    }

    function build(t) {
      const r = CO.researchOf(t), rv = CO.review(t), u = state.uniMap[t] || {}, f = CO.dat(t, 'fundamentals');
      const p = CO.priceOf(t), c = r && rv ? CO.callOf(t, false) : null;
      const ready = !!f;
      const pages = [];

      if (c) {
        const fill = (x) => CO.fill(t, x);
        // Page 1: the call
        pages.push(h('div', { class: 'rp-grid' },
          h('div', { class: 'rp-main' },
            h('div', { class: 'rp-title' },
              h('div', { class: 'rp-eyebrow' }, [u.sector, t, 'Initiation of coverage'].filter(Boolean).join(' · ')),
              h('div', { class: 'rp-callline' }, h('span', { class: 'rp-pill ' + RK(c.rating) }, c.rating), `Price target ${fmt.px(c.pt)}`),
              h('h1', null, nameOf(t) + ': ' + rv.title),
              h('p', { class: 'rp-lead' }, fill(rv.lead))),
            h('div', { class: 'rp-args' }, rv.arguments.map((a) => h('p', null, h('b', null, a.label + '. '), fill(a.text)))),
            sec('Why ' + c.rating.toLowerCase(), h('p', null, fill(rv.call_reason))),
            sec('Our estimates against consensus', estimatesTable(t))),
          callBox(t)));
        // Page 2: performance, financials, balance sheet, management
        pages.push([
          sec('Share price against the sector, rebased to 100', relChart(t), perfTable(t)),
          sec('Financial summary', finTable(t)),
          sec('Balance sheet', h('p', null, rv.balance.read), h('ul', { class: 'rp-list' }, rv.balance.facts.map((x) => h('li', null, x)))),
          sec('Management, governance and earnings quality', mgmt(t))]);
        // Page 3: thesis, framework, valuation
        pages.push([
          sec('Investment thesis', ...rv.thesis_long.map((x) => h('p', null, fill(x)))),
          sec('The Moat Monitor framework', frameworkTable(t)),
          sec('Valuation and price target', targetBuild(t))]);
        // Page 4: business, peers
        pages.push([
          sec('How it makes money', h('p', null, rv.model), h('div', { class: 'rp-earn' }, rv.how_it_earns.map((x) => h('div', null, h('b', null, x.k), h('span', null, x.v))))),
          segTable(t) ? sec(rv.mix.axis === 'segment' ? 'Segment performance' : 'Revenue by line', segTable(t)) : null,
          sec('Moat and competitive position', h('div', { class: 'rp-two' }, h('p', null, h('b', null, `Moat ${rv.moat.rating} / 5. `), rv.moat.sources.join('; ') + '. ' + rv.moat.threat), h('p', null, h('b', null, 'Position. '), rv.position))),
          peerTable(t) ? sec('Valuation against peers', peerTable(t), h('div', { class: 'rp-two' }, h('p', null, h('b', null, 'For the premium. '), rv.peer_read.why_premium), h('p', null, h('b', null, 'Against it. '), rv.peer_read.why_not))) : null]);
        // Page 5: risks, catalysts, assumptions, disclosures
        pages.push([
          sec('Risks to our rating and price target: downside', riskTable(t)),
          rv.upside_risks ? sec('Risks to our rating and price target: upside', table(['Upside risk', 'How it would show'], rv.upside_risks.map((x) => [h('b', null, x.cause), x.how]), { cls: 'wrap-last' })) : null,
          catalysts(t) ? sec('Catalysts', catalysts(t)) : null,
          sec('Assumptions behind the scenarios', assumptions(t)),
          disclosures(t)]);
      } else {
        const title = h('div', { class: 'rp-title' },
          h('div', { class: 'rp-eyebrow' }, [u.sector, t, 'Basic view'].filter(Boolean).join(' · ')),
          h('h1', null, nameOf(t)),
          h('p', { class: 'rp-head' }, r ? r.header.one_liner : 'A data-led snapshot from filings and market data. Full research, and so a rating and price target, has not been built for this name yet.'));
        pages.push(h('div', { class: 'rp-grid' }, h('div', { class: 'rp-main' }, title, priceChart(t) ? sec('Share price, one year', priceChart(t)) : null, sec('Financial summary', finTable(t))), h('aside', { class: 'rp-side' }, h('h3', null, 'Key data'), keyData(t))));
        pages.push([sec('Management and earnings quality', mgmt(t)), disclosures(t)]);
      }
      const of = pages.length;
      return h('div', { class: 'rp' },
        !ready ? h('p', { class: 'rp-loading' }, 'Loading the latest data for this report…') : null,
        pages.map((body, i) => pageWrap(t, i + 1, of, body)));
    }

    function disclosures(t) {
      const r = CO.researchOf(t), rv = CO.review(t);
      const src = ((rv && rv.sources) || []).concat((r && r.sources) || []);
      return h('section', { class: 'rp-sec rp-disc' }, h('h3', null, 'Sources and disclosures'),
        src.length ? h('ul', { class: 'rp-src' }, src.map((s) => h('li', null, `${s.title} (${s.date})`))) : null,
        h('p', null, 'Generated by Moat Monitor, an AI native equity research tool, from company filings (SEC EDGAR) and market data (Yahoo Finance, delayed). Written analysis is dated and refreshed after each earnings release; numbers refresh automatically. The rating and price target are outputs of a disclosed model whose every assumption can be disputed in the app; they are not a recommendation from a licensed adviser. This report is for research and discussion only and is not investment advice or an offer to buy or sell any security.'),
        rv ? h('p', null, `Review basis: ${rv.basis}`) : null);
    }

    return { build };
  };
})();
